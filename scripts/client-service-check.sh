#!/bin/sh
# Run on the actual client/VPN path, not the hosting router. No software installs.
set -u
umask 077
HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
TARGETS=${1:-"$HERE/service-targets.txt"}
[ -r "$TARGETS" ] || { echo 'Missing service-targets.txt (generated by router diagnostic)';exit 2; }
OUT=$(mktemp -d "${TMPDIR:-/tmp}/homegate-client-network-XXXXXX") || exit 1
LOG="$OUT/client.log"
printf 'role=client\nUTC=%s\nRun with the same VPN/node as the failing browser. Direct probes bypass environment proxies; VPN routes still apply.\n' "$(date -u '+%Y-%m-%dT%H:%M:%SZ')" >"$LOG"
command -v curl >/dev/null 2>&1 || { echo 'curl is required; no software installed';exit 2; }
for family in 4 6;do
 printf '\negress_direct_family=%s\n' "$family" >>"$LOG"
 curl "-$family" --noproxy '*' --silent --show-error --connect-timeout 5 --max-time 10 'https://www.cloudflare.com/cdn-cgi/trace' >"$OUT/egress-$family.log" 2>&1
 rc=$?;grep -E '^(ip|loc|colo|warp)=' "$OUT/egress-$family.log" >>"$LOG" || true
 printf 'curl_exit=%s\n' "$rc" >>"$LOG"
done
printf '\negress_environment_proxy\n' >>"$LOG"
curl --silent --show-error --connect-timeout 5 --max-time 10 'https://www.cloudflare.com/cdn-cgi/trace' >"$OUT/egress-proxy.log" 2>&1
rc=$?;grep -E '^(ip|loc|colo|warp)=' "$OUT/egress-proxy.log" >>"$LOG" || true
printf 'curl_exit=%s\n' "$rc" >>"$LOG"
index=0
while IFS= read -r url || [ -n "$url" ];do
 [ -n "$url" ] || continue
 case "$url" in *[!a-zA-Z0-9.:/-]*|*'@'*) printf 'SKIP invalid target\n' >>"$LOG";continue;;esac
 case "$url" in http://*|https://*) ;;*) printf 'SKIP invalid scheme\n' >>"$LOG";continue;;esac
 index=$((index+1));[ "$index" -le 32 ] || break
 host=${url#*://};host=${host%%/*};host=${host%%:*}
 printf '\nTARGET=%s\n' "$url" >>"$LOG"
 if command -v nslookup >/dev/null 2>&1;then nslookup "$host" >>"$LOG" 2>&1;fi
 for route in direct environment-proxy;do
  for family in 4 6;do
   set -- "-$family";[ "$route" != direct ] || set -- "$@" --noproxy '*'
   printf 'route=%s family=%s\n' "$route" "$family" >>"$LOG"
   curl "$@" --head --silent --show-error --connect-timeout 5 --max-time 10 --output /dev/null \
    --write-out 'http_code=%{http_code}\nremote_ip=%{remote_ip}\nssl_verify_result=%{ssl_verify_result}\n' "$url" >>"$LOG" 2>&1
   printf 'curl_exit=%s\n' "$?" >>"$LOG"
  done
 done
done <"$TARGETS"
printf '\nProxy probes may constrain the proxy connection family, not the ultimate target family. Browser proxy/PAC and mobile VPN can differ; correlate with router records.\n' >>"$LOG"
printf 'Cloudflare loc is request-egress geolocation, not physical location proof.\n' >>"$LOG"
tar -czf "$OUT.tar.gz" -C "$(dirname "$OUT")" "$(basename "$OUT")" || exit 1
echo "REPORT $OUT.tar.gz"
